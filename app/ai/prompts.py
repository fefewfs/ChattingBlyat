def create_training_system_prompt(mode: str, persona: str, skill_focus: str = None, level: int = 1) -> str:
    config = TRAINING_MODE_PROMPTS.get(mode, TRAINING_MODE_PROMPTS["quick_round"])
    prompt = f"{config['prompt']}\n\nТвой персонаж: {persona}."
    if skill_focus:
        prompt += f"\n\nОсобый фокус тренировки: {skill_focus}."
    prompt += f"\n\nУровень сложности: {level}/6. Чем выше уровень, тем сложнее клиент."
    prompt += "\n\nВАЖНО: Первое сообщение должно быть реакцией на обращение продавца. Будь естественен."
    return prompt


